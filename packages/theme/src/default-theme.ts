export const THEME_REGISTRY: Record<string, YumiaTheme> = {
  default: defaultTheme,
  cyberpunk: cyberpunkTheme,
  minimal: minimalTheme,
  corporate: corporateTheme,
  terminal: terminalTheme,
  academic: academicTheme,
};

export function resolveTheme(
  themeNameOrRef?: string | { name: string; overrides?: ThemeOverrides },
  explicitOverrides?: ThemeOverrides
): YumiaTheme {
  const name =
    typeof themeNameOrRef === 'string' ? themeNameOrRef : themeNameOrRef?.name || 'default';

  const baseTheme = THEME_REGISTRY[name.toLowerCase()] || defaultTheme;
  const refOverrides = typeof themeNameOrRef === 'object' ? themeNameOrRef.overrides : undefined;

  const mergedOverrides: ThemeOverrides = {
    ...refOverrides,
    ...explicitOverrides,
    colors: { ...baseTheme.colors, ...refOverrides?.colors, ...explicitOverrides?.colors },
    typography: {
      ...baseTheme.typography,
      ...refOverrides?.typography,
      ...explicitOverrides?.typography,
      sizes: {
        ...baseTheme.typography.sizes,
        ...refOverrides?.typography?.sizes,
        ...explicitOverrides?.typography?.sizes,
      },
      weights: {
        ...baseTheme.typography.weights,
        ...refOverrides?.typography?.weights,
        ...explicitOverrides?.typography?.weights,
      },
      lineHeights: {
        ...baseTheme.typography.lineHeights,
        ...refOverrides?.typography?.lineHeights,
        ...explicitOverrides?.typography?.lineHeights,
      },
    },
    spacing: {
      ...baseTheme.spacing,
      ...refOverrides?.spacing,
      ...explicitOverrides?.spacing,
      safeArea: {
        ...baseTheme.spacing.safeArea,
        ...refOverrides?.spacing?.safeArea,
        ...explicitOverrides?.spacing?.safeArea,
      },
    },
    radius: {
      ...baseTheme.radius,
      ...refOverrides?.radius,
      ...explicitOverrides?.radius,
    },
    shadows: {
      ...baseTheme.shadows,
      ...refOverrides?.shadows,
      ...explicitOverrides?.shadows,
    },
    components: {
      ...baseTheme.components,
      ...refOverrides?.components,
      ...explicitOverrides?.components,
    },
  };

  return {
    ...baseTheme,
    ...mergedOverrides,
  } as YumiaTheme;
}

export function createTheme(overrides: ThemeOverrides & { name: string }): YumiaTheme {
  return resolveTheme(overrides.name, overrides);
}
